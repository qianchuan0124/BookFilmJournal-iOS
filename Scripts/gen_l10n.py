#!/usr/bin/env python3
"""Generate BookFilmJournal L10n.swift from zh-Hans Localizable.strings."""
import re
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
STRINGS = ROOT / "BookFilmJournal-iOS/zh-Hans.lproj/Localizable.strings"
OUTPUT = ROOT / "BookFilmJournal-iOS/L10n/L10n.swift"

NAMESPACES = {
    "common": "Common",
    "theme": "Theme",
    "auth": "Auth",
    "error": "Error",
    "tab": "Tab",
    "media": "Media",
    "stats": "Stats",
    "records": "Records",
    "doulist": "Doulist",
    "plan": "Plan",
    "report": "Report",
    "settings": "Settings",
    "sync": "Sync",
    "wordcount": "WordCount",
    "explore": "Explore",
    "cloud": "Cloud",
    "data": "Data",
    "recycle": "Recycle",
    "toast": "Toast",
}
ORDER = ["Common", "Theme", "Auth", "Error", "Tab", "Media", "Stats", "Records", "Doulist", "Plan", "Report", "Settings", "Sync", "WordCount", "Explore", "Cloud", "Data", "Recycle", "Toast"]
LINE = re.compile(r'^\s*"([^"]+)"\s*=\s*"(.*)";\s*$')

def camel(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(word[:1].upper() + word[1:] for word in parts[1:])

def placeholders(value: str):
    return re.findall(r"%(?:@|d|ld|lu|f|\.\d+f)", value)

def main() -> None:
    entries = []
    for line in STRINGS.read_text(encoding="utf-8").splitlines():
        m = LINE.match(line)
        if m:
            entries.append((m.group(1), m.group(2)))
    groups = {}
    for key, value in entries:
        prefix, _, rest = key.partition("_")
        namespace = NAMESPACES.get(prefix)
        if namespace is None:
            raise SystemExit(f"Unknown namespace for key: {key}")
        groups.setdefault(namespace, []).append((camel(rest), key, value))
    lines = [
        "// Generated by Scripts/gen_l10n.py from zh-Hans.lproj/Localizable.strings.",
        "// Do not edit by hand.",
        "",
        "import Foundation",
        "",
        "enum L10n {",
    ]
    for namespace in ORDER:
        items = sorted(groups.get(namespace, []), key=lambda item: item[0])
        if not items:
            continue
        lines.append(f"    enum {namespace} {{")
        for name, key, value in items:
            tokens = placeholders(value)
            lines.append(f"        /// {value}")
            if not tokens:
                lines.append(f'        static let {name} = L10nCore.string("{key}")')
            else:
                params = []
                args = []
                for index, token in enumerate(tokens):
                    if token == "%d":
                        params.append(f"_ p{index + 1}: Int")
                        args.append(f"p{index + 1}")
                    elif token in ("%f",) or token.startswith("%."):
                        params.append(f"_ p{index + 1}: Double")
                        args.append(f"p{index + 1}")
                    else:
                        params.append(f"_ p{index + 1}: Any")
                        args.append(f"String(describing: p{index + 1})")
                paramText = ", ".join(params)
                argText = ", ".join(args)
                lines.append(f"        static func {name}({paramText}) -> String {{")
                lines.append(f'            L10nCore.string("{key}", {argText})')
                lines.append("        }")
        lines.append("    }")
        lines.append("")
    if lines[-1] == "":
        lines.pop()
    lines += ["}", ""]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {OUTPUT} ({len(entries)} strings)")

if __name__ == "__main__":
    main()
